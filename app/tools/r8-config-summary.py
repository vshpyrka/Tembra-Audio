#!/usr/bin/env python3
"""A Markdown summary of R8's Configuration Analyzer report, for the CI run page.

Usage: tools/r8-config-summary.py <configanalyzer.pb> [--top N]

`assembleRelease` writes the report beside the mapping (AGP 9.3): `androidApp/build/outputs/mapping/release/
configanalyzer.{html,pb}`. This prints the three scores (the share of live classes, fields and methods that R8 may
optimize, rename and remove), any global option that switches R8 off, any keep rule from the app's own files, and the
N rules that keep the most. The scores are computed the way Google's r8-analyzer skill computes them, so they compare
with docs/research/r8-configuration-analysis.md.

The CI runner has no protobuf package, so the report is read with the standard library: the field numbers below
follow R8's keep_radius.proto (message com.android.tools.r8.blastradius.proto.BlastRadiusContainer).
Tests: python3 -m unittest discover -s tools -p 'test_r8_config_summary.py'
"""
import argparse
import os
import sys

# BlastRadiusContainer
FILE_ORIGIN_TABLE, MAVEN_COORDINATE_TABLE = 1, 3
KEPT_CLASS_TABLE, KEPT_FIELD_TABLE, KEPT_METHOD_TABLE = 9, 10, 11
KEEP_CONSTRAINTS_TABLE, KEEP_RULE_TABLE, GLOBAL_RULE_TABLE, BUILD_INFO = 12, 13, 14, 15
# KeepConstraint enum
DONT_OBFUSCATE, DONT_OPTIMIZE, DONT_SHRINK = 0, 1, 2


def _varint(buf, pos):
    result = shift = 0
    while True:
        byte = buf[pos]
        pos += 1
        result |= (byte & 0x7F) << shift
        if byte < 0x80:
            return result, pos
        shift += 7


def _fields(buf):
    """Yields (field number, wire type, value) of one message; a value is an int or bytes."""
    pos = 0
    while pos < len(buf):
        key, pos = _varint(buf, pos)
        number, wire = key >> 3, key & 7
        if wire == 0:
            value, pos = _varint(buf, pos)
        elif wire == 2:
            length, pos = _varint(buf, pos)
            value, pos = buf[pos:pos + length], pos + length
        elif wire == 1:
            value, pos = buf[pos:pos + 8], pos + 8
        elif wire == 5:
            value, pos = buf[pos:pos + 4], pos + 4
        else:
            raise ValueError(f"unsupported protobuf wire type {wire} in field {number}")
        yield number, wire, value


def _message(buf):
    """One message as {field number: [values]}, repeated fields in order."""
    fields = {}
    for number, wire, value in _fields(buf):
        fields.setdefault(number, []).append((wire, value))
    return fields


def _int(msg, number):
    values = msg.get(number)
    return values[-1][1] if values else 0


def _str(msg, number):
    values = msg.get(number)
    return values[-1][1].decode("utf-8") if values else ""


def _sub(msg, number):
    values = msg.get(number)
    return _message(values[-1][1]) if values else {}


def _ints(msg, number):
    """A repeated int32 or enum field, packed or not."""
    out = []
    for wire, value in msg.get(number, []):
        if wire == 0:
            out.append(value)
            continue
        pos = 0
        while pos < len(value):
            item, pos = _varint(value, pos)
            out.append(item)
    return out


def _table(container, number):
    return [_message(value) for _, value in container.get(number, [])]


def _origin_label(rule, files, mavens):
    """Where a rule comes from, and whether it is in the app's own files (the same split as r8-analyzer)."""
    origin = _sub(rule, 4)
    file = files.get(_int(origin, 1), {})
    path = _str(file, 2)
    coordinate = _sub(file, 3)
    if coordinate and not _str(coordinate, 3):
        coordinate = mavens.get(_int(coordinate, 1), {})
    maven = ":".join(part for part in (_str(coordinate, 2), _str(coordinate, 3), _str(coordinate, 4)) if part)
    if maven:
        return maven, False
    if "/transformed/" in path:
        return "library rules in " + path.split("/transformed/", 1)[1], False
    if _int(file, 4) or "default_proguard_files" in path or path.startswith("Android Gradle plugin"):
        return "AGP defaults", False
    if "/intermediates/generated_proguard_file/" in path or "/intermediates/aapt_proguard_file/" in path:
        return "generated by the build", False
    if os.path.isabs(path):
        relative = os.path.relpath(path)
        path = path if relative.startswith("..") else relative
    line = _int(origin, 2)
    return (f"{path}:{line}" if line else path), True


def summarize(data, top=5):
    """The Markdown summary of one serialized BlastRadiusContainer."""
    container = _message(data)
    files = {_int(f, 1): f for f in _table(container, FILE_ORIGIN_TABLE)}
    mavens = {_int(m, 1): m for m in _table(container, MAVEN_COORDINATE_TABLE)}
    constraints = {_int(c, 1): set(_ints(c, 2)) for c in _table(container, KEEP_CONSTRAINTS_TABLE)}
    rules = _table(container, KEEP_RULE_TABLE)
    rule_constraints = {_int(r, 1): constraints.get(_int(r, 3), set()) for r in rules}
    global_rules = [_str(g, 2) for g in _table(container, GLOBAL_RULE_TABLE)]

    blocked = {DONT_OPTIMIZE: 0, DONT_OBFUSCATE: 0, DONT_SHRINK: 0}
    kept_items = 0
    for number in (KEPT_CLASS_TABLE, KEPT_FIELD_TABLE, KEPT_METHOD_TABLE):
        for item in _table(container, number):
            kept_items += 1
            kept_by = _ints(item, 4)
            for flag in blocked:
                if any(flag in rule_constraints.get(rule, set()) for rule in kept_by):
                    blocked[flag] += 1
    build_info = _sub(container, BUILD_INFO)
    live = _int(build_info, 4) + _int(build_info, 5) + _int(build_info, 6)
    denominator = live or kept_items

    def score(flag, option):
        if any(option in source.lower() for source in global_rules):
            return 0.0
        return max(0.0, 100.0 - (blocked[flag] / denominator * 100 if denominator else 0.0))

    rows = []
    app_rules = []
    for rule in rules:
        radius = _sub(rule, 5)
        classes, fields, methods = len(_ints(radius, 2)), len(_ints(radius, 3)), len(_ints(radius, 4))
        label, in_app = _origin_label(rule, files, mavens)
        row = (classes + fields + methods, _str(rule, 2), label, classes, fields, methods)
        rows.append(row)
        if in_app:
            app_rules.append(row)
    rows.sort(key=lambda r: r[0], reverse=True)

    out = [
        "## R8 configuration",
        "",
        "| Optimization | Obfuscation | Shrinking |",
        "|---|---|---|",
        f"| {score(DONT_OPTIMIZE, '-dontoptimize'):.2f} % | {score(DONT_OBFUSCATE, '-dontobfuscate'):.2f} % "
        f"| {score(DONT_SHRINK, '-dontshrink'):.2f} % |",
        "",
        f"The share of the {live:,} live classes, fields and methods that R8 may optimize, rename and remove. "
        f"{len(rules)} keep rules, {len(app_rules)} of them in the app's own files; "
        f"{len(global_rules)} global options. Reference values: `docs/research/r8-configuration-analysis.md`. "
        "The full report is this run's `configanalyzer.html` artifact.",
    ]
    if global_rules:
        out += ["", "**Global options that switch part of R8 off:**", ""]
        out += [f"- `{_cell(source)}`" for source in global_rules]
    if app_rules:
        out += ["", "### Keep rules in the app's own files", ""] + _rule_table(sorted(app_rules, reverse=True))
    out += ["", f"### The {min(top, len(rows))} keep rules that keep the most", ""] + _rule_table(rows[:top])
    return "\n".join(out) + "\n"


def _cell(source):
    """A rule as one table cell: its first line, at most 100 characters, without pipes or backticks."""
    first = " ".join(source.split("\n", 1)[0].split())
    if "\n" in source.strip() or len(first) > 100:
        first = first[:100].rstrip() + " …"
    return first.replace("|", "\\|").replace("`", "'")


def _rule_table(rows):
    lines = ["| Rule | From | Classes | Fields | Methods |", "|---|---|---|---|---|"]
    for _, source, label, classes, fields, methods in rows:
        lines.append(f"| `{_cell(source)}` | {label} | {classes} | {fields} | {methods} |")
    return lines


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("report", help="configanalyzer.pb from the R8 build")
    parser.add_argument("--top", type=int, default=5, help="how many of the widest keep rules to list (default 5)")
    args = parser.parse_args(argv)
    with open(args.report, "rb") as report:
        sys.stdout.write(summarize(report.read(), args.top))


if __name__ == "__main__":
    main()
