#!/usr/bin/env python3
"""Generates the navigation's Tuner and Metronome glyphs as Compose vector resources (hand-drawn artwork, not Material
Symbols, which has neither a tuning fork nor a metronome; owner's choice of 2026-10-17).

Both are drawn on the Material Symbols 24 x 24 grid in the weight of Material Symbols Outlined 400: 2-unit strokes with
flat ends and round joins, each line its own stroked `<path>` with a literal white stroke the Icon composable tints
(Compose renders stroked vector paths the same way on Android and iOS).

- tuning_fork: two prongs joined by a U and a stem, with one sound arc on each side of the prongs.
- metronome: a pyramid body, the scale plate across its lower part and the rod pivoting on the plate. The rod leaves the
  body through its right edge, and the edge is broken where it crosses, so the crossing stays legible at 24 dp.

Usage: python3 tools/make-nav-glyphs.py [--preview <dir>]
Output: shared/ui/src/commonMain/composeResources/drawable/ic_{tuning_fork,metronome}_24.xml, and the metronome again as
the Android notification's status-bar icon androidApp/src/main/res/drawable/ic_stat_metronome.xml (idempotent:
re-running overwrites identically); with --preview, also <dir>/glyphs.svg.json (glyph name -> a list of SVG path data, to be
stroked 2 units wide) and <dir>/glyphs.html (a preview sheet at 24, 32 and 96 px).
"""
import json
import os
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(SCRIPT_DIR, "..", "shared", "ui", "src", "commonMain", "composeResources", "drawable")
STATUS_ICON = os.path.join(SCRIPT_DIR, "..", "androidApp", "src", "main", "res", "drawable", "ic_stat_metronome.xml")
STROKE = 2.0


def fmt(v):
    s = ("%.2f" % v).rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def tuning_fork():
    return [
        "M9.5,3V10.5A2.5,2.5 0,0 0,14.5 10.5V3",  # prongs and the U that joins them
        "M12,13V21.5",  # stem
        "M5.6,4.5A6,6 0,0 0,5.6 10.5",  # sound arc, left
        "M18.4,4.5A6,6 0,0 1,18.4 10.5",  # sound arc, right
    ]


def metronome(top=(9.4, 14.6, 3.0), bottom=(4.4, 19.6, 21.0), plate_y=14.0, rod_end=(18.6, 4.2), gap=2.0):
    """The body is a trapezoid from `top` (left x, right x, y) to `bottom`; the rod runs from the plate's middle to
    `rod_end`; the right edge leaves out `gap` units above and below the point where the rod crosses it."""
    (tl, tr, ty), (bl, br, by) = top, bottom

    def right_x(y):
        return tr + (br - tr) * (y - ty) / (by - ty)

    def left_x(y):
        return tl + (bl - tl) * (y - ty) / (by - ty)

    px, py = 12.0, plate_y
    ex, ey = rod_end
    lo, hi = ey, py  # bisect for the height where the rod meets the right edge
    for _ in range(60):
        mid = (lo + hi) / 2
        if px + (ex - px) * (py - mid) / (py - ey) > right_x(mid):
            lo = mid
        else:
            hi = mid
    cross = (lo + hi) / 2
    y1, y2 = cross - gap, cross + gap
    return [
        "M%s,%sL%s,%sH%sL%s,%sH%sL%s,%s" % (
            fmt(right_x(y1)), fmt(y1), fmt(tr), fmt(ty), fmt(tl), fmt(bl), fmt(by), fmt(br), fmt(right_x(y2)), fmt(y2)),
        "M%s,%sH%s" % (fmt(left_x(py) + 1), fmt(py), fmt(right_x(py) - 1)),  # scale plate
        "M%s,%sL%s,%s" % (fmt(px), fmt(py), fmt(ex), fmt(ey)),  # rod
    ]


GLYPHS = [
    ("tuning_fork", "tuning fork (Tuner)", tuning_fork()),
    ("metronome", "metronome (Metronome)", metronome()),
]


def vector_xml(name, paths, header=None):
    body = "".join(
        '  <path\n      android:strokeColor="#FFFFFFFF"\n      android:strokeWidth="%s"\n'
        '      android:strokeLineJoin="round"\n      android:pathData="%s"/>\n' % (fmt(STROKE), d)
        for d in paths
    )
    header = header or 'Tembra navigation glyph "%s"; generated by tools/make-nav-glyphs.py, do not edit' % name
    return (
        '<!-- %s -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp"\n'
        '    android:height="24dp"\n'
        '    android:viewportWidth="24"\n'
        '    android:viewportHeight="24">\n'
        "%s</vector>\n" % (header, body)
    )


def svg_paths(paths):
    """Path data in SVG syntax (the vector's commas become spaces) for HTML previews and the design screens."""
    return [d.replace(",", " ") for d in paths]


def write_preview(directory):
    os.makedirs(directory, exist_ok=True)
    data = {name: svg_paths(paths) for name, _, paths in GLYPHS}
    with open(os.path.join(directory, "glyphs.svg.json"), "w") as f:
        json.dump(data, f, indent=2)
        f.write("\n")
    tiles = []
    for name, label, _ in GLYPHS:
        inner = "".join('<path d="%s"/>' % d for d in data[name])
        svg = ('<svg viewBox="0 0 24 24" width="%d" height="%d" fill="none" stroke="#fff" stroke-width="2" '
               'stroke-linejoin="round">%s</svg>')
        tiles.append("<figure>%s%s%s<figcaption>%s<br>ic_%s_24</figcaption></figure>"
                     % (svg % (96, 96, inner), svg % (24, 24, inner), svg % (32, 32, inner), label, name))
    html = (
        "<!doctype html><meta charset=utf-8><style>body{margin:16px;background:#222;font:11px sans-serif;color:#ccc;"
        "display:grid;grid-template-columns:repeat(2,200px);gap:12px}figure{margin:0;background:#111114;padding:8px;"
        "display:flex;flex-wrap:wrap;align-items:flex-end;gap:8px}svg{outline:1px dashed #333}figcaption{width:100%%}"
        "</style>%s" % "".join(tiles)
    )
    with open(os.path.join(directory, "glyphs.html"), "w") as f:
        f.write(html)


def main(argv):
    for name, _, paths in GLYPHS:
        out = os.path.join(OUT_DIR, "ic_%s_24.xml" % name)
        with open(out, "w") as f:
            f.write(vector_xml(name, paths))
        print("wrote " + os.path.relpath(out, os.path.join(SCRIPT_DIR, "..")))
    status = vector_xml("metronome", metronome(), header="Status-bar icon of the metronome notification: the navigation's "
                        "metronome glyph, white; generated by tools/make-nav-glyphs.py, do not edit")
    with open(STATUS_ICON, "w") as f:
        f.write(status)
    print("wrote " + os.path.relpath(STATUS_ICON, os.path.join(SCRIPT_DIR, "..")))
    if len(argv) == 2 and argv[0] == "--preview":
        write_preview(argv[1])
    elif argv:
        raise SystemExit("usage: make-nav-glyphs.py [--preview <dir>]")


if __name__ == "__main__":
    main(sys.argv[1:])
